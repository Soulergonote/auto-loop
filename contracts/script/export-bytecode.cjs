// Compiles LeverageExecutorV2 (and v1, and LeverageExecutorMorpho) with solc-js using foundry.toml's settings (0.8.27, cancun, optimizer 200 runs,
// no metadata hash) and writes their creation bytecode to app/src/executorBytecode.ts, which the app deploys from
// the user's wallet. Needs lib/ (bash script/setup.sh) and the solc 0.8.27 npm package:
//   NODE_PATH=/path/with/node_modules node script/export-bytecode.cjs
const fs = require('fs')
const path = require('path')
const solc = require('solc')

const root = path.join(__dirname, '..')
const remappings = fs
  .readFileSync(path.join(root, 'remappings.txt'), 'utf8')
  .split('\n')
  .filter(Boolean)
  .map((l) => l.split('='))
if (!solc.version().startsWith('0.8.27')) throw new Error(`solc 0.8.27 attendu, ${solc.version()} trouvé`)

function findImports(p) {
  for (const [from, to] of remappings) if (p.startsWith(from)) return { contents: fs.readFileSync(path.join(root, to + p.slice(from.length)), 'utf8') }
  const f = path.join(root, p)
  if (fs.existsSync(f)) return { contents: fs.readFileSync(f, 'utf8') }
  return { error: `introuvable : ${p}` }
}

function compile(file, name) {
  const input = {
    language: 'Solidity',
    sources: { [file]: { content: fs.readFileSync(path.join(root, file), 'utf8') } },
    settings: {
      evmVersion: 'cancun',
      optimizer: { enabled: true, runs: 200 },
      metadata: { bytecodeHash: 'none' },
      outputSelection: { [file]: { [name]: ['evm.bytecode.object'] } },
    },
  }
  const out = JSON.parse(solc.compile(JSON.stringify(input), { import: findImports }))
  const errors = (out.errors ?? []).filter((e) => e.severity === 'error')
  if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join('\n'))
  return out.contracts[file][name].evm.bytecode.object
}

// v2 is what the app deploys; v1 is kept so that executors already deployed with it are still recognised
const v1 = compile('src/LeverageExecutor.sol', 'LeverageExecutor')
const v2 = compile('src/LeverageExecutorV2.sol', 'LeverageExecutorV2')
const morpho = compile('src/LeverageExecutorMorpho.sol', 'LeverageExecutorMorpho')
const target = path.join(root, '../app/src/executorBytecode.ts')
fs.writeFileSync(
  target,
  `// Generated by contracts/script/export-bytecode.cjs (solc ${solc.version()}, cancun, optimizer 200). Do not edit.\n` +
    `export const EXECUTOR_BYTECODE_V2 = '0x${v2}' as const\n` +
    `export const EXECUTOR_BYTECODE_V1 = '0x${v1}' as const\n` +
    `export const EXECUTOR_BYTECODE_MORPHO = '0x${morpho}' as const\n`,
)
console.log(`${target}: v2 ${v2.length / 2} octets, v1 ${v1.length / 2} octets, Morpho ${morpho.length / 2} octets`)
